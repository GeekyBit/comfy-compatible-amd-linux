# setup-comfy.sh
# Install and operate a user-run ComfyUI instance through one `comfy` command.
set -Eeuo pipefail

APP_NAME="comfy"
CLI_VERSION="1.22.0"
DEFAULT_COMFY_VERSION="0.39.2"
DEFAULT_PORT="8188"
DEFAULT_GPU="0"
DEFAULT_HSA="1"
CONFIG_ROOT="${XDG_CONFIG_HOME:-$HOME/.config}/comfy"
CONFIG_FILE="$CONFIG_ROOT/config.env"
CLI_VENV="${HOME}/.venvs/comfy-cli"
SELF_PATH="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/$(basename "${BASH_SOURCE[0]}")"

say() { printf '%s\n' "$*"; }
warn() { printf 'Warning: %s\n' "$*" >&2; }
die() { printf 'Error: %s\n' "$*" >&2; exit 1; }
command_exists() { command -v "$1" >/dev/null 2>&1; }

ask() {
    local prompt="$1" default="${2:-}" answer
    if [[ -n "$default" ]]; then
        read -r -p "$prompt [$default]: " answer
        printf '%s' "${answer:-$default}"
    else
        while :; do
            read -r -p "$prompt: " answer
            [[ -n "$answer" ]] && { printf '%s' "$answer"; return; }
            say "A value is required."
        done
    fi
}

ask_yes_no() {
    local prompt="$1" default="${2:-y}" answer
    while :; do
        if [[ "$default" == y ]]; then
            read -r -p "$prompt [Y/n]: " answer
            answer="${answer:-y}"
        else
            read -r -p "$prompt [y/N]: " answer
            answer="${answer:-n}"
        fi
        case "${answer,,}" in
            y|yes) return 0 ;;
            n|no) return 1 ;;
            *) say "Please answer yes or no." ;;
        esac
    done
}

load_os() {
    OS_ID=unknown
    OS_NAME=Linux
    if [[ -r /etc/os-release ]]; then
        # shellcheck disable=SC1091
        . /etc/os-release
        OS_ID="${ID:-unknown}"
        OS_NAME="${PRETTY_NAME:-Linux}"
    fi
}

rocm_info_command() {
    if command_exists rocminfo; then
        command -v rocminfo
    elif [[ -x /opt/rocm/bin/rocminfo ]]; then
        printf '%s' /opt/rocm/bin/rocminfo
    else
        return 1
    fi
}

check_dependencies() {
    local missing=() py_version
    command_exists bash || missing+=("bash")
    command_exists python3 || missing+=("python3")
    command_exists git || missing+=("git")
    command_exists curl || missing+=("curl")
    command_exists python3 && ! python3 -c 'import venv' >/dev/null 2>&1 && missing+=("python3-venv / Python venv support")
    rocm_info_command >/dev/null 2>&1 || missing+=("ROCm rocminfo")
    [[ -e /dev/kfd ]] || missing+=("/dev/kfd (ROCm kernel device)")
    compgen -G '/dev/dri/renderD*' >/dev/null || missing+=("/dev/dri/renderD* (render device)")

    if command_exists python3; then
        py_version="$(python3 -c 'import sys; print(f"{sys.version_info.major}.{sys.version_info.minor}")')"
        say "Python detected: $py_version"
    fi

    if ((${#missing[@]})); then
        say ""
        say "This setup cannot continue because these prerequisites are missing:"
        printf '  - %s\n' "${missing[@]}"
        say ""
        say "Install prerequisites yourself, then run this installer again. This script does not install missing system dependencies."
        case "$OS_ID" in
            arch|cachyos)
                say "Arch-family starting point: sudo pacman -S python git curl rocminfo"
                say "Install ROCm using the official instructions for your distribution and GPU."
                ;;
            ubuntu|debian)
                say "Ubuntu/Debian starting point: sudo apt install python3 python3-venv python3-pip git curl"
                say "Install ROCm and rocminfo using AMD's official instructions for your distribution and GPU."
                ;;
            *)
                say "Install Python 3 with venv support, git, curl, ROCm, rocminfo, /dev/kfd, and a render device."
                ;;
        esac
        exit 1
    fi
}

workspace_python() {
    local workspace="$1"
    if [[ -x "$workspace/.venv/bin/python" ]]; then
        printf '%s' "$workspace/.venv/bin/python"
    elif [[ -x "$workspace/venv/bin/python" ]]; then
        printf '%s' "$workspace/venv/bin/python"
    else
        return 1
    fi
}

write_model_paths() {
    mkdir -p "$COMFYUI_MODELS_ROOT"
    cat > "$COMFYUI_EXTRA_MODELS" <<EOF
# Generated by setup-comfy.sh.
# This file selects model locations; it does not download model files.
comfy_models:
  base_path: $COMFYUI_MODELS_ROOT
  checkpoints: checkpoints/
  diffusion_models: diffusion_models/
  text_encoders: text_encoders/
  clip: clip/
  vae: vae/
  loras: loras/
  controlnet: controlnet/
  upscale_models: upscale_models/
  embeddings: embeddings/
  unet: unet/
EOF
}

save_config() {
    mkdir -p "$CONFIG_ROOT" "$COMFYUI_OUTPUT"
    write_model_paths
    {
        printf 'COMFY_CLI=%q\n' "$COMFY_CLI"
        printf 'COMFYUI_HOME=%q\n' "$COMFYUI_HOME"
        printf 'COMFYUI_VERSION=%q\n' "$COMFYUI_VERSION"
        printf 'COMFYUI_GPU=%q\n' "$COMFYUI_GPU"
        printf 'COMFYUI_SCOPE=%q\n' "$COMFYUI_SCOPE"
        printf 'COMFYUI_HOST=%q\n' "$COMFYUI_HOST"
        printf 'COMFYUI_INTERFACE=%q\n' "$COMFYUI_INTERFACE"
        printf 'COMFYUI_SUBNET=%q\n' "$COMFYUI_SUBNET"
        printf 'COMFYUI_PORT=%q\n' "$COMFYUI_PORT"
        printf 'COMFYUI_MODELS_ROOT=%q\n' "$COMFYUI_MODELS_ROOT"
        printf 'COMFYUI_OUTPUT=%q\n' "$COMFYUI_OUTPUT"
        printf 'COMFYUI_EXTRA_MODELS=%q\n' "$COMFYUI_EXTRA_MODELS"
        printf 'HSA_TOOLS_DISABLE_REGISTER=%q\n' "$HSA_TOOLS_DISABLE_REGISTER"
        printf 'FIREWALL_BACKEND=%q\n' "${FIREWALL_BACKEND:-none}"
    } > "$CONFIG_FILE"
    chmod 600 "$CONFIG_FILE"
}

load_config() {
    [[ -r "$CONFIG_FILE" ]] || die "ComfyUI is not configured. Run: comfy -setup"
    # shellcheck disable=SC1090
    . "$CONFIG_FILE"
}

choose_network_scope() {
    local current_scope="${COMFYUI_SCOPE:-system}" choice entries i selected
    say ""
    say "Where should the ComfyUI web page be reachable?"
    say "  1) This system only: 127.0.0.1"
    say "  2) The local network: choose one of this system's LAN addresses"
    choice="$(ask "Choose access scope" "$([[ "$current_scope" == network ]] && printf 2 || printf 1)")"
    case "$choice" in
        1)
            COMFYUI_SCOPE=system
            COMFYUI_HOST=127.0.0.1
            COMFYUI_INTERFACE=""
            COMFYUI_SUBNET=""
            ;;
        2)
            command_exists ip || die "The 'ip' command is required to choose a LAN address. Install iproute2, then run comfy -setup again."
            mapfile -t entries < <(ip -o -4 addr show scope global | awk '{print $2"|"$4}')
            ((${#entries[@]})) || die "No non-loopback IPv4 address was found. Configure the network, then run comfy -setup again."
            say "Available LAN addresses:"
            for i in "${!entries[@]}"; do printf '  %d) %s\n' "$((i + 1))" "${entries[$i]}"; done
            selected="$(ask "Choose the LAN address" "1")"
            [[ "$selected" =~ ^[0-9]+$ ]] && ((selected >= 1 && selected <= ${#entries[@]})) || die "Invalid LAN address selection."
            IFS='|' read -r COMFYUI_INTERFACE COMFYUI_HOST <<< "${entries[$((selected - 1))]}"
            COMFYUI_SUBNET="$(ip -4 route show dev "$COMFYUI_INTERFACE" proto kernel scope link | awk 'NR==1 {print $1}')"
            COMFYUI_SCOPE=network
            say "ComfyUI will bind to $COMFYUI_HOST on interface $COMFYUI_INTERFACE."
            [[ -n "$COMFYUI_SUBNET" ]] || warn "Could not determine the LAN subnet automatically; the firewall may need manual configuration."
            ;;
        *) die "Choose 1 or 2." ;;
    esac
}

configure_firewall() {
    [[ "$COMFYUI_SCOPE" == network ]] || { say "Local-only mode selected; no firewall rule is needed."; return; }
    FIREWALL_BACKEND=none
    if command_exists ufw && ufw status 2>/dev/null | grep -qi active; then
        FIREWALL_BACKEND=ufw
        say "Active UFW firewall detected."
        if ask_yes_no "Allow TCP port $COMFYUI_PORT from the selected local network?" y; then
            if [[ -n "$COMFYUI_INTERFACE" && -n "$COMFYUI_SUBNET" ]]; then
                sudo ufw allow in on "$COMFYUI_INTERFACE" from "$COMFYUI_SUBNET" to any port "$COMFYUI_PORT" proto tcp
            else
                sudo ufw allow "$COMFYUI_PORT/tcp"
            fi
        else
            warn "No UFW rule was added. Remote access may be blocked."
        fi
    elif command_exists firewall-cmd && firewall-cmd --state >/dev/null 2>&1; then
        FIREWALL_BACKEND=firewalld
        say "Active firewalld detected."
        if ask_yes_no "Allow TCP port $COMFYUI_PORT through firewalld's default zone?" y; then
            local zone
            zone="$(firewall-cmd --get-default-zone)"
            sudo firewall-cmd --zone="$zone" --permanent --add-port="$COMFYUI_PORT/tcp"
            sudo firewall-cmd --reload
        else
            warn "No firewalld rule was added. Remote access may be blocked."
        fi
    else
        say "No active UFW or firewalld installation was detected. No firewall rule was changed."
    fi
}

write_systemd_unit() {
    local unit_dir="$HOME/.config/systemd/user"
    command_exists systemctl || { warn "systemctl is unavailable; no startup service was created."; return; }
    mkdir -p "$unit_dir"
    cat > "$unit_dir/comfy.service" <<EOF
[Unit]
Description=User-run ComfyUI
After=default.target

[Service]
Type=simple
ExecStart=$HOME/.local/bin/comfy -start --foreground
ExecStop=$HOME/.local/bin/comfy -stop
Restart=on-failure
RestartSec=5

[Install]
WantedBy=default.target
EOF
    systemctl --user daemon-reload
    if ask_yes_no "Enable and start ComfyUI automatically for this user?" n; then
        systemctl --user enable --now comfy.service
        say "comfy.service is enabled for this user."
    else
        say "Startup service created but left disabled."
    fi
}

configure_startup() {
    command_exists systemctl || { say "systemd user services are unavailable on this system."; return; }
    local unit="$HOME/.config/systemd/user/comfy.service"
    if [[ -e "$unit" ]]; then
        if ask_yes_no "Keep ComfyUI enabled as a user startup service?" n; then
            systemctl --user enable --now comfy.service
            say "comfy.service is enabled."
        elif ask_yes_no "Disable the ComfyUI user startup service?" y; then
            systemctl --user disable --now comfy.service || true
            say "comfy.service is disabled."
        fi
    elif ask_yes_no "Create an optional systemd user service for automatic startup?" n; then
        write_systemd_unit
    fi
}

setup_menu() {
    load_config
    say "ComfyUI setup"
    say "This changes launch settings only. It does not choose or download models."
    COMFYUI_GPU="$(ask "GPU visibility value" "$COMFYUI_GPU")"
    COMFYUI_PORT="$(ask "Web port" "$COMFYUI_PORT")"
    COMFYUI_MODELS_ROOT="$(ask "Model root directory" "$COMFYUI_MODELS_ROOT")"
    COMFYUI_OUTPUT="$(ask "Output directory" "$COMFYUI_OUTPUT")"
    choose_network_scope
    if [[ "${HSA_TOOLS_DISABLE_REGISTER:-1}" == 1 ]] && ask_yes_no "Use HSA_TOOLS_DISABLE_REGISTER=1 for the tested idle-CPU workaround?" y; then
        HSA_TOOLS_DISABLE_REGISTER=1
    elif [[ "${HSA_TOOLS_DISABLE_REGISTER:-0}" != 1 ]] && ask_yes_no "Use HSA_TOOLS_DISABLE_REGISTER=1 for the tested idle-CPU workaround?" n; then
        HSA_TOOLS_DISABLE_REGISTER=1
    else
        HSA_TOOLS_DISABLE_REGISTER=0
    fi
    save_config
    configure_firewall
    configure_startup
    say "Settings saved. Start with: comfy -start"
}

copy_examples() {
    local source_dir="$1" destination="$COMFYUI_HOME/workflows/rdna2-comfyui-guide"
    mkdir -p "$destination"
    if compgen -G "$source_dir/examples/*.json" >/dev/null; then
        cp -n "$source_dir"/examples/*.json "$destination"/
        say "Example workflow files copied to $destination"
    else
        warn "No bundled example JSON files were found beside the installer."
    fi
}

install_all() {
    load_os
    check_dependencies
    say "ComfyUI user setup"
    say "This installs the Comfy CLI and ComfyUI application. It never downloads model weights."

    local workspace version cli_py wpy index
    workspace="$(ask "Where should the user-run ComfyUI application live?" "$HOME/ComfyUI")"
    version="$(ask "ComfyUI version" "$DEFAULT_COMFY_VERSION")"
    COMFYUI_HOME="$workspace"
    COMFYUI_VERSION="$version"
    COMFYUI_GPU="$(ask "GPU visibility value" "$DEFAULT_GPU")"
    COMFYUI_PORT="$(ask "Web port" "$DEFAULT_PORT")"
    COMFYUI_MODELS_ROOT="$(ask "Model root directory" "$workspace/models")"
    COMFYUI_OUTPUT="$(ask "Output directory" "$workspace/output")"
    COMFYUI_EXTRA_MODELS="$CONFIG_ROOT/model-paths.yaml"
    HSA_TOOLS_DISABLE_REGISTER="$DEFAULT_HSA"
    COMFYUI_INTERFACE=""
    COMFYUI_SUBNET=""
    choose_network_scope
    if ! ask_yes_no "Use HSA_TOOLS_DISABLE_REGISTER=1 for the tested idle-CPU workaround?" y; then HSA_TOOLS_DISABLE_REGISTER=0; fi

    mkdir -p "$(dirname "$CLI_VENV")"
    if [[ ! -x "$CLI_VENV/bin/python" ]]; then
        python3 -m venv "$CLI_VENV"
    fi
    cli_py="$CLI_VENV/bin/python"
    "$cli_py" -m pip install --upgrade pip
    "$cli_py" -m pip install "comfy-cli==$CLI_VERSION"
    COMFY_CLI="$CLI_VENV/bin/comfy"

    say "Installing ComfyUI into $COMFYUI_HOME ..."
    "$COMFY_CLI" --workspace="$COMFYUI_HOME" install
    "$COMFY_CLI" --workspace="$COMFYUI_HOME" update comfy --version "$COMFYUI_VERSION"

    wpy="$(workspace_python "$COMFYUI_HOME")" || die "ComfyUI's Python environment was not found."
    if ! "$wpy" -c 'import torch; raise SystemExit(0 if torch.cuda.is_available() and torch.version.hip else 1)'; then
        index="https://download.pytorch.org/whl/rocm7.2"
        say "ComfyUI is installed, but ROCm-enabled PyTorch was not detected."
        say "Install the appropriate PyTorch ROCm wheel for your ROCm version, for example:"
        say "  $wpy -m pip install torch torchvision torchaudio --index-url $index"
        die "Install PyTorch manually, verify it with the troubleshooting guide, and run this installer again."
    fi

    save_config
    copy_examples "$(cd "$(dirname "$SELF_PATH")" && pwd)"
    mkdir -p "$HOME/.local/bin"
    install -m 755 "$SELF_PATH" "$HOME/.local/bin/comfy"
    if [[ ":$PATH:" != *":$HOME/.local/bin:"* ]]; then
        warn "$HOME/.local/bin is not currently in PATH. Open a new shell or run: export PATH=\"$HOME/.local/bin:\$PATH\""
    fi
    configure_firewall

    if ask_yes_no "Create an optional systemd user service for automatic startup?" n; then
        write_systemd_unit
    fi

    say ""
    say "Setup complete. Model weights were not downloaded."
    say "Use: comfy -start, comfy -stop, comfy -status, comfy -setup, comfy -update, or comfy -help"
}

api_url() { printf 'http://%s:%s' "$COMFYUI_HOST" "$COMFYUI_PORT"; }

start_comfy() {
    load_config
    local foreground=0
    [[ "${2:-}" == --foreground ]] && foreground=1
    export HIP_VISIBLE_DEVICES="$COMFYUI_GPU"
    export HSA_TOOLS_DISABLE_REGISTER="${HSA_TOOLS_DISABLE_REGISTER:-1}"
    "$COMFY_CLI" stop >/dev/null 2>&1 || true
    if ((foreground)); then
        exec "$COMFY_CLI" --workspace="$COMFYUI_HOME" launch -- \
            --listen "$COMFYUI_HOST" --port "$COMFYUI_PORT" \
            --output-directory "$COMFYUI_OUTPUT" \
            --extra-model-paths-config "$COMFYUI_EXTRA_MODELS"
    fi
    "$COMFY_CLI" --workspace="$COMFYUI_HOME" launch --background -- \
        --listen "$COMFYUI_HOST" --port "$COMFYUI_PORT" \
        --output-directory "$COMFYUI_OUTPUT" \
        --extra-model-paths-config "$COMFYUI_EXTRA_MODELS"
    for _ in $(seq 1 180); do
        if curl -fsS "$(api_url)/system_stats" >/dev/null 2>&1; then
            say "ComfyUI is ready."
            say "Web page: $(api_url)/"
            return 0
        fi
        sleep 1
    done
    "$COMFY_CLI" logs >&2 || true
    die "ComfyUI did not become ready."
}

stop_comfy() {
    load_config
    if command_exists systemctl && systemctl --user is-active --quiet comfy.service 2>/dev/null; then
        systemctl --user stop comfy.service
    fi
    "$COMFY_CLI" stop >/dev/null 2>&1 || true
    say "The ComfyUI instance managed by this setup was stopped."
}

status_comfy() {
    load_config
    say "ComfyUI status"
    say "Application: $COMFYUI_HOME"
    say "GPU visibility: $COMFYUI_GPU"
    say "Access scope: $COMFYUI_SCOPE"
    say "Web page: $(api_url)/"
    say "Model root: $COMFYUI_MODELS_ROOT"
    say "Output directory: $COMFYUI_OUTPUT"
    say "ComfyUI version setting: $COMFYUI_VERSION"
    say ""
    if curl -fsS "$(api_url)/system_stats" | python3 -m json.tool 2>/dev/null; then :; else say "ComfyUI API: not reachable"; fi
    say "Queue:"
    curl -fsS "$(api_url)/queue" | python3 -m json.tool 2>/dev/null || say "  unavailable"
    say "Recent workflow history:"
    curl -fsS "$(api_url)/history?max_items=3" | python3 -m json.tool 2>/dev/null || say "  unavailable"
    say "Exact cached model names are not guaranteed by the ComfyUI API; status reports the configured model locations and live queue/system data."
}

update_comfy() {
    load_config
    local was_running=0 backup stamp
    if curl -fsS "$(api_url)/system_stats" >/dev/null 2>&1; then was_running=1; fi
    stamp="$(date +%Y%m%d-%H%M%S)"
    backup="$CONFIG_ROOT/backups/$stamp"
    mkdir -p "$backup"
    cp -a "$CONFIG_FILE" "$backup/config.env"
    [[ -f "$COMFYUI_EXTRA_MODELS" ]] && cp -a "$COMFYUI_EXTRA_MODELS" "$backup/"
    say "Updating ComfyUI only. ROCm, PyTorch, models, and custom nodes will not be changed."
    ((was_running)) && stop_comfy
    if ! "$COMFY_CLI" --workspace="$COMFYUI_HOME" update comfy; then
        warn "ComfyUI update failed. Configuration backup: $backup"
        ((was_running)) && start_comfy || true
        return 1
    fi
    say "ComfyUI update completed. Configuration backup: $backup"
    ((was_running)) && start_comfy
}

help_comfy() {
    cat <<EOF
ComfyUI launcher and setup helper

  comfy -start [--foreground]  Start the configured ComfyUI instance
  comfy -stop                  Stop the instance managed by this setup
  comfy -status                Show settings, URL, queue, system stats, and history
  comfy -setup                 Change storage, GPU, web access, firewall, and startup settings
  comfy -update                Update ComfyUI only, preserving ROCm/PyTorch/models/custom nodes
  comfy -help                  Show this help

The installer configures a user-run application. It does not download model weights.
Model selection belongs in workflow JSON files. Model locations are configured with
comfy -setup. Local-system mode binds to 127.0.0.1; local-network mode binds to a
selected LAN address and asks before changing an active firewall.
EOF
}

load_os
if [[ "$(basename "$SELF_PATH")" == "$APP_NAME" ]]; then
    default_action="-help"
else
    default_action="install"
fi
case "${1:-$default_action}" in
    install) install_all ;;
    -start) start_comfy "$@" ;;
    -stop) stop_comfy ;;
    -status) status_comfy ;;
    -setup) setup_menu ;;
    -update) update_comfy ;;
    -help|help|-h|--help) help_comfy ;;
    *) help_comfy; exit 2 ;;
esac
